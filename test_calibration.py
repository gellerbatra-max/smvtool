class TestSyntheticGenerator:
    def test_batch_is_schema_valid(self, tax, mcat, synthetic_batch):
        loader = tsl.TimeStudyLoader(tax, mcat)
        batch_for_loader = {k: v for k, v in synthetic_batch.items() if k != "_ground_truth"}
        lr = loader.load_batch_dict(batch_for_loader)
        assert lr.n_observations_seen == len(synthetic_batch["observations"])
        assert not lr.rejections

    def test_batch_flagged_synthetic(self, synthetic_batch):
        assert synthetic_batch["method"] == "SYNTHETIC"
        assert all(o.get("observed_s", 0) > 0 for o in synthetic_batch["observations"])

    def test_observation_kinds_present(self, loaded_rows):
        kinds = {r["kind"] for r in loaded_rows}
        assert kinds <= {"element_observation", "seam_observation", "cycle_observation"}
        assert len(kinds) >= 2, "synthetic generator should produce a mix of observation kinds"

    def test_reproducible_with_seed(self, tax, mcat):
        b1 = cf.generate_synthetic_batch(tax, mcat, n_operators=3, n_per_operator=5, seed=123)
        b2 = cf.generate_synthetic_batch(tax, mcat, n_operators=3, n_per_operator=5, seed=123)
        obs1 = [o["observed_s"] for o in b1["observations"]]
        obs2 = [o["observed_s"] for o in b2["observations"]]
        assert obs1 == obs2


