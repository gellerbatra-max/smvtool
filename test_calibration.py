class TestDiagnostics:
    def test_residual_table_covers_all_rows(self, tax, mcat, loaded_rows):
        result = cf.calibrate_all(tax, mcat, loaded_rows)
        tax_fitted = ht.Taxonomy(result.fitted_tax_raw)
        resid = cd.residual_table(tax_fitted, mcat, result.fitted_motion_params, loaded_rows)
        assert len(resid) == len(loaded_rows)
        assert (resid["predicted_s"] > 0).all()
        assert (resid["observed_s"] > 0).all()

    def test_error_summary_has_expected_columns(self, tax, mcat, loaded_rows):
        result = cf.calibrate_all(tax, mcat, loaded_rows)
        tax_fitted = ht.Taxonomy(result.fitted_tax_raw)
        resid = cd.residual_table(tax_fitted, mcat, result.fitted_motion_params, loaded_rows)
        by_kind = cd.error_summary_by_kind(resid)
        assert {"kind", "n", "MAPE_pct", "RMSE_log", "bias_pct"} <= set(by_kind.columns)
        assert (by_kind["MAPE_pct"] >= 0).all()

    def test_fit_recovers_low_error_on_own_synthetic_data(self, tax, mcat, loaded_rows):
        """Sanity floor: fitting the engine to noise generated FROM the
        engine's own predictions (see generate_synthetic_batch's noise_sigma_log
        default of 0.12) should recover single-digit-to-low-teens MAPE, not
        blow up. This catches a broken fit (e.g. a sign error) that would
        otherwise pass the narrower unit tests above."""
        result = cf.calibrate_all(tax, mcat, loaded_rows)
        tax_fitted = ht.Taxonomy(result.fitted_tax_raw)
        resid = cd.residual_table(tax_fitted, mcat, result.fitted_motion_params, loaded_rows)
        by_kind = cd.error_summary_by_kind(resid)
        assert (by_kind["MAPE_pct"] < 30.0).all(), f"MAPE unexpectedly high: {by_kind}"

    def test_cross_validated_mape_runs_and_is_positive(self, tax, mcat, loaded_rows):
        cv = cd.cross_validated_mape(tax, mcat, loaded_rows, k=3, seed=1)
        assert cv["mean_MAPE_pct"] is not None
        assert cv["mean_MAPE_pct"] > 0
        assert len(cv["folds"]) == 3

    def test_diagnostics_figure_renders(self, tax, mcat, loaded_rows, tmp_path):
        result = cf.calibrate_all(tax, mcat, loaded_rows)
        tax_fitted = ht.Taxonomy(result.fitted_tax_raw)
        resid = cd.residual_table(tax_fitted, mcat, result.fitted_motion_params, loaded_rows)
        by_kind = cd.error_summary_by_kind(resid)
        cv = cd.cross_validated_mape(tax, mcat, loaded_rows, k=3, seed=1)
        out_path = str(tmp_path / "diag.png")
        fig = cd.render_diagnostics_figure(resid, by_kind, result.coverage, cv, out_path)
        import os
        assert os.path.exists(out_path)
        assert os.path.getsize(out_path) > 1000


