class TestFitScope1:
    def test_sparse_rows_keep_defaults(self, tax, mcat):
        """A single observation must never be enough to move a global
        constant off its shipped default -- that is what MIN_OBS_FOR_FIT
        guards against."""
        p0 = es.MotionParams()
        one_row = [{
            "kind": "element_observation", "factory_id": "F1", "operator_id": "OP1",
            "observed_s": 3.0, "method": "SYNTHETIC",
            "detail": {"element_code": "HAG",
                       "params": {"distance_cm": 25.0, "precision_class": "P2"}},
        }]
        outcomes, p_fitted, cov = cf.fit_scope1(tax, mcat, p0, one_row)
        assert all(o.used_default for o in outcomes.values())
        assert p_fitted.as_dict() == p0.as_dict()

    def test_sufficient_rows_move_off_default_toward_truth(self, tax, mcat, loaded_rows):
        """Perturb g_0 in a copy of the taxonomy, generate synthetic rows
        from THAT perturbed taxonomy, then fit scope 1 from the shipped
        (unperturbed) starting point and check the fit recovers something
        closer to the true perturbed value than the shipped default is."""
        import json
        true_g0 = 0.35   # shipped default is smaller; see element_taxonomy.json
        perturbed_raw = json.loads(json.dumps(tax.raw))
        for gp in perturbed_raw["global_parameters"]:
            if gp["symbol"] == "g_0":
                shipped_default = gp["default"]
                gp["default"] = true_g0
        tax_perturbed = ht.Taxonomy(perturbed_raw)

        batch = cf.generate_synthetic_batch(tax_perturbed, mcat, n_operators=5,
                                             n_per_operator=25, seed=99, noise_sigma_log=0.05)
        loader = tsl.TimeStudyLoader(tax, mcat)   # validate against the SHIPPED taxonomy's element signatures
        rows = loader.load_batch_dict({k: v for k, v in batch.items() if k != "_ground_truth"}).rows

        outcomes, p_fitted, cov = cf.fit_scope1(tax, mcat, es.MotionParams(), rows)
        g0_outcome = outcomes["g_0"]
        assert not g0_outcome.used_default, "g_0 should have enough grasp-phase rows to fit"
        dist_before = abs(shipped_default - true_g0)
        dist_after = abs(g0_outcome.fitted_value - true_g0)
        assert dist_after < dist_before, (
            f"fit moved g_0 further from truth: shipped={shipped_default}, "
            f"fitted={g0_outcome.fitted_value}, true={true_g0}"
        )

    def test_fit_respects_plausible_range_bounds(self, tax, mcat, loaded_rows):
        outcomes, p_fitted, cov = cf.fit_scope1(tax, mcat, es.MotionParams(), loaded_rows)
        for sym, outcome in outcomes.items():
            if outcome.used_default:
                continue
            meta = tax.global_meta.get(sym)
            if meta and meta.get("plausible_range"):
                lo, hi = meta["plausible_range"]
                assert lo <= outcome.fitted_value <= hi, f"{sym} fit {outcome.fitted_value} outside [{lo},{hi}]"

    def test_motionparams_bounds_respected(self, mcat, loaded_rows, tax):
        outcomes, p_fitted, cov = cf.fit_scope1(tax, mcat, es.MotionParams(), loaded_rows)
        for field_name, (lo, hi) in cf.MOTIONPARAMS_BOUNDS.items():
            val = getattr(p_fitted, field_name)
            assert lo <= val <= hi, f"{field_name}={val} outside bounds [{lo},{hi}]"


