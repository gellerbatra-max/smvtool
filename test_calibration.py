class TestSensitivity:
    def test_every_symbol_present(self, tax, mcat, loaded_rows):
        p0 = es.MotionParams()
        cov = cf.sensitivity_report(tax, mcat, p0, loaded_rows)
        expected = set(cf.SCOPE1_TAXONOMY_SYMBOLS) | set(cf.MOTIONPARAMS_BOUNDS)
        assert set(cov["symbol"]) == expected

    def test_g_0_sensitive_to_grasp_rows(self, tax, mcat, loaded_rows):
        """g_0 is the grasp-phase intercept used by every element with a
        grasp phase (HAM, HAB, HFC, ...); with a healthy synthetic batch it
        must show up as sensitive on at least a handful of rows."""
        p0 = es.MotionParams()
        cov = cf.sensitivity_report(tax, mcat, p0, loaded_rows)
        row = cov[cov["symbol"] == "g_0"].iloc[0]
        assert row["n_supporting_rows"] > 0

    def test_b_steer_sensitive_to_steer_phase_elements(self, tax, mcat, loaded_rows):
        """b_steer (the global steering-law slope) is used by every element
        whose phase_program includes a 'steer' phase -- not only HGD's
        seam-guide usage but also HFD/HAL/HFC/HTO/HSM, which are all
        element_observation rows. It is legitimately sensitive to BOTH
        observation kinds; this test checks it is sensitive to at least one
        seam_observation row when seam rows are present, not that it is
        seam-exclusive."""
        p0 = es.MotionParams()
        cov = cf.sensitivity_report(tax, mcat, p0, loaded_rows)
        row = cov[cov["symbol"] == "b_steer"].iloc[0]
        has_seam_rows = any(r["kind"] == "seam_observation" for r in loaded_rows)
        if row["n_supporting_rows"] > 0 and has_seam_rows:
            assert "seam_observation" in row["observation_kinds"]

    def test_zero_rows_yields_zero_coverage(self, tax, mcat):
        p0 = es.MotionParams()
        cov = cf.sensitivity_report(tax, mcat, p0, [])
        assert (cov["n_supporting_rows"] == 0).all()


