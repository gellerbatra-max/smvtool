class TestFactoryReferenceFabric:
    def test_no_measurements_keeps_global_default(self, loaded_rows):
        out = cf.fit_factory_reference_fabric(loaded_rows)
        for factory_id, syms in out.items():
            for symbol, outcome in syms.items():
                assert outcome.used_default, "synthetic rows carry no environment.measured_* fields"
                assert outcome.fitted_value is None

    def test_sufficient_measurements_are_averaged(self):
        rows = []
        for i in range(6):
            rows.append({
                "factory_id": "FACT-A", "operator_id": "OPX", "kind": "element_observation",
                "observed_s": 1.0,
                "environment": {"measured_B_uNm": 8.0 + i * 0.1},
            })
        out = cf.fit_factory_reference_fabric(rows, min_obs=5)
        outcome = out["FACT-A"]["B_ref"]
        assert not outcome.used_default
        assert outcome.fitted_value == pytest.approx(np.mean([8.0 + i * 0.1 for i in range(6)]))

    def test_different_factories_kept_separate(self):
        rows = [
            {"factory_id": "A", "operator_id": "O1", "kind": "element_observation",
             "observed_s": 1.0, "environment": {"measured_B_uNm": v}}
            for v in [8.0] * 5
        ] + [
            {"factory_id": "B", "operator_id": "O2", "kind": "element_observation",
             "observed_s": 1.0, "environment": {"measured_B_uNm": v}}
            for v in [12.0] * 5
        ]
        out = cf.fit_factory_reference_fabric(rows, min_obs=5)
        assert out["A"]["B_ref"].fitted_value == pytest.approx(8.0)
        assert out["B"]["B_ref"].fitted_value == pytest.approx(12.0)


