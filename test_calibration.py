class TestOperatorGamma:
    def test_recovers_operator_ranking(self, tax, mcat):
        """With well-separated true Gamma_skill values and low noise, the
        fitted per-operator multipliers must at least preserve the RANK
        ORDER of the true values -- this is the property line managers
        actually rely on ('who is fast, who is slow'), and a much lower bar
        than exact recovery."""
        true_gamma = {"OP1": 0.85, "OP2": 0.95, "OP3": 1.05, "OP4": 1.15, "OP5": 1.25}
        batch = cf.generate_synthetic_batch(
            tax, mcat, n_operators=5, n_per_operator=30, seed=11,
            true_gamma_by_operator=true_gamma, noise_sigma_log=0.05,
        )
        loader = tsl.TimeStudyLoader(tax, mcat)
        rows = loader.load_batch_dict({k: v for k, v in batch.items() if k != "_ground_truth"}).rows

        outcomes, p_fitted, _ = cf.fit_scope1(tax, mcat, es.MotionParams(), rows)
        import json
        fitted_raw = json.loads(json.dumps(tax.raw))
        gp_by_symbol = {gp["symbol"]: gp for gp in fitted_raw["global_parameters"]}
        for sym, o in outcomes.items():
            if not o.used_default and sym in gp_by_symbol:
                gp_by_symbol[sym]["default"] = o.fitted_value
        tax_fitted = ht.Taxonomy(fitted_raw)

        gamma_fitted, summary, resid_df = cf.fit_operator_gamma(tax_fitted, mcat, p_fitted, rows)
        factory_id = batch["factory_id"]
        true_order = sorted(true_gamma, key=true_gamma.get)
        fitted_order = sorted(true_gamma, key=lambda op: gamma_fitted.get(f"{factory_id}::{op}", 1.0))
        assert true_order == fitted_order, (
            f"rank order not preserved: true={true_order} fitted={fitted_order} "
            f"raw fitted values={gamma_fitted}"
        )

    def test_empty_rows_returns_empty(self, tax, mcat):
        gamma, summary, df = cf.fit_operator_gamma(tax, mcat, es.MotionParams(), [])
        assert gamma == {}
        assert df.empty


